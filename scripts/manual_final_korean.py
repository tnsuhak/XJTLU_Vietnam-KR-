def apply(path:Path):
    soup=BeautifulSoup(path.read_text(encoding='utf-8'),'html.parser')
    skip={'script','style','svg','path','noscript','code','pre'}
    mapping=PAGE.get(path.relative_to(ROOT).as_posix(),{})
    for node in list(soup.find_all(string=True)):
        if isinstance(node,Comment) or not node.parent or node.parent.name in skip: continue
        raw=str(node)
        stripped=' '.join(raw.split())
        new=None
        if stripped in mapping: new=mapping[stripped]
        elif stripped in GLOBAL: new=GLOBAL[stripped]
        if new is not None:
            lead=raw[:len(raw)-len(raw.lstrip())]
            trail=raw[len(raw.rstrip()):]
            node.replace_with(NavigableString(lead+new+trail))
    # Meta/attributes also need common terminology cleanup.
    for tag in soup.find_all(True):
        for attr in ('content','aria-label','alt','title'):
            val=tag.get(attr)
            if not isinstance(val,str): continue
            for old,new in GLOBAL.items(): val=val.replace(old,new)
            for old,new in mapping.items(): val=val.replace(old,new)
            val=val.replace('장학비','장학금').replace('학금','학비')
            val=val.replace('99,000원','99,000 RMB').replace('99.000원','99.000 RMB').replace('99,000만원','99,000 RMB').replace('99.000만원','99.000 RMB')
            val=val.replace('시안 지아토ング-리버풀대학교','시안교통리버풀대학교').replace('시안 지아토ング 리버풀대학교','시안교통리버풀대학교')
            tag[attr]=val
    path.write_text(str(soup),encoding='utf-8')

