pages=sorted(Path('.').glob('*.html'))+sorted(Path('news').glob('*.html'))
for path in pages:
    rel=path.as_posix()
    mapping={}
    mapping.update(GLOBAL)
    mapping.update(NEWS_GLOBAL)
    mapping.update(PAGE.get(rel,{}))
    soup=BeautifulSoup(path.read_text(encoding='utf-8'),'html.parser')
    for node in list(soup.find_all(string=True)):
        if isinstance(node,Comment) or not node.parent or node.parent.name in SKIP:
            continue
        raw=str(node)
        key=' '.join(raw.split())
        if key in mapping:
            lead=raw[:len(raw)-len(raw.lstrip())]
            trail=raw[len(raw.rstrip()):]
            node.replace_with(NavigableString(lead+mapping[key]+trail))
    # Safe grammar/terminology fixes in attributes and remaining raw HTML text.
    text=str(soup)
    for old,new in [
        ('리버풀대학교과','리버풀대학교와'),('리버풀대학교은','리버풀대학교는'),('리버풀대학교이','리버풀대학교가'),
        ('20262027','2026–2027'),('학료','학비'),('HCMD 외교부','호치민시 외교부'),
        ('시안 자이오통-리버풀대학교','시안교통리버풀대학교'),('시안 자이오통 대학교',"Xi\'an Jiaotong University"),
    ]:
        text=text.replace(old,new)
    path.write_text(text,encoding='utf-8')
