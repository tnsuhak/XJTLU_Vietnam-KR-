for rel,mapping in MAP.items():
    p=Path(rel)
    if not p.exists(): continue
    soup=BeautifulSoup(p.read_text(encoding='utf-8'),'html.parser')
    for node in list(soup.find_all(string=True)):
        if isinstance(node,Comment) or not node.parent or node.parent.name in {'script','style','svg','path','noscript','code','pre'}: continue
        raw=str(node); key=' '.join(raw.split())
        if key in mapping:
            lead=raw[:len(raw)-len(raw.lstrip())]; trail=raw[len(raw.rstrip()):]
            node.replace_with(NavigableString(lead+mapping[key]+trail))
    # Critical money units and obvious leftovers in metadata/visible HTML.
    text=str(soup)
    for old,new in [('99,000만원','99,000 RMB'),('99.000만원','99.000 RMB'),('99,000원','99,000 RMB'),('99.000원','99.000 RMB'),('도저','쑤저우'),('도천','쑤저우'),('타이칸','타이창'),('학비과','학비와')]:
        text=text.replace(old,new)
    p.write_text(text,encoding='utf-8')
